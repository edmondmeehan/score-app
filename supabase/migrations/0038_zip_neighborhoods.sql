-- Public lookup: neighborhood, borough and an approximate center point (neighborhood if mapped, else borough).
create or replace function public.zip_lookup(p_zip text) returns jsonb
language sql stable security definer set search_path = public as $$
  with z as (select trim(p_zip) as zip)
  select jsonb_build_object(
    'zip', z.zip,
    'nyc', n.zip is not null,
    'borough', n.borough,
    'neighborhood', coalesce(zn.name, mp.name),
    'lat', coalesce(mp.lat, b.lat),
    'lng', coalesce(mp.lng, b.lng),
    'precise', mp.lat is not null
  )
  from z
  left join nyc_zip_codes n on n.zip = z.zip
  left join zip_neighborhoods zn on zn.zip = z.zip
  left join zip_places zp on zp.zip = z.zip
  left join map_places mp on mp.key = zp.place_key
  left join map_places b on b.key = 'borough:' || replace(lower(n.borough), ' ', '-');
$$;
grant execute on function public.zip_lookup(text) to anon, authenticated;

